import { spawnSync as spawnSync5 } from "child_process";
import { existsSync } from "fs";
import { resolve } from "path";
function synthesizeOrientationBlock(cwd = process.cwd()) {
  if (!existsSync(resolve(cwd, ".seeds")) && !existsSync(resolve(cwd, ".mulch"))) {
    return;
  }
  const sections = ["[ORIENTATION]"];
  try {
    const readyProc = spawnSync5("seeds", ["ready", "--json"], { cwd, encoding: "utf-8" });
    if (readyProc.status === 0 && readyProc.stdout) {
      const parsed = JSON.parse(readyProc.stdout);
      const issues = parsed.issues || [];
      if (issues.length > 0) {
        sections.push(`\u2022 Ready issues (${issues.length}): ` + issues.slice(0, 3).map((i) => `${i.id} (${i.title})`).join(", "));
      }
    }
  } catch {}
  try {
    const inProgProc = spawnSync5("seeds", ["list", "--status", "in_progress", "--json"], {
      cwd,
      encoding: "utf-8"
    });
    if (inProgProc.status === 0 && inProgProc.stdout) {
      const parsed = JSON.parse(inProgProc.stdout);
      const issues = parsed.issues || [];
      if (issues.length > 0) {
        sections.push(`\u2022 In progress: ${issues.map((i) => `${i.id}: ${i.title}`).join(", ")}`);
      }
    }
  } catch {}
  sections.push("\u2022 Grove commands: sd ready | sd show <id> | ml query architecture | ml prime");
  return sections.join(`
`);
}

// .pi/extensions/_shared/inject.ts
function injectMode(env = process.env) {
  return env.LITTLE_CODER_INJECT_MODE === "system" ? "system" : "message";
}
function injectionResult(customType, block, systemPrompt = "", env = process.env) {
  if (!block)
    return;
  if (injectMode(env) === "system") {
    return { systemPrompt: systemPrompt + block };
  }
  return { message: { customType, content: block, display: false } };
}
function makeDedupe(env = process.env) {
  let last = null;
  return (block) => {
    if (injectMode(env) === "system")
      return true;
    if (block === last)
      return false;
    last = block;
    return true;
  };
}

